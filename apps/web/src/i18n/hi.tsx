function habit(avg: number | null): string {
  if (avg === null) return "अभी तक कोई बिल नहीं चुकाया";
  if (avg === 0) return "समय पर भुगतान करते हैं";
  if (avg < 0) return `आमतौर पर ${-avg} दिन पहले भुगतान करते हैं`;
  return `आमतौर पर ${avg} दिन देर से भुगतान करते हैं`;
}

