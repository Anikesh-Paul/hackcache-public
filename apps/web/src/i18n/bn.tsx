function habit(avg: number | null): string {
  if (avg === null) return "এখনও কোনো বিল মেটানো হয়নি";
  if (avg === 0) return "সময়মতো টাকা দেন";
  if (avg < 0) return `সাধারণত ${-avg} দিন আগে টাকা দেন`;
  return `সাধারণত ${avg} দিন দেরিতে টাকা দেন`;
}

